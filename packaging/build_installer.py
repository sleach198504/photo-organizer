def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skip-payload", action="store_true", help="reuse build/installer-payload from the last run")
    args = parser.parse_args()

    if not ISCC.is_file():
        raise SystemExit(f"Inno Setup was not found at {ISCC}. See docs/PACKAGING.md.")

    if not args.skip_payload or not PAYLOAD.is_dir():
        sys.argv = ["build_payload.py", "--channel", "installer", "--out", str(PAYLOAD)]
        if build_payload.main() != 0:
            return 1

    DIST.mkdir(parents=True, exist_ok=True)
    SCRIPT.write_text(
        ISS.format(
            version=__version__, app_id=APP_ID, old_key=OLD_SETUP_KEY, payload=PAYLOAD, dist=DIST,
            license=ROOT / "LICENSE", icon=ROOT / "app" / "web" / "static" / "icons" / "app.ico",
        ),
        encoding="utf-8",
    )
    print("Compiling the installer (this takes a few minutes)", flush=True)
    result = subprocess.run([str(ISCC), str(SCRIPT)], text=True)
    if result.returncode != 0:
        return result.returncode
    setup = DIST / f"PhotoOrganizer-{__version__}-Setup.exe"
    print(f"\nBuilt {setup}  ({setup.stat().st_size / (1 << 20):,.0f} MB)", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
